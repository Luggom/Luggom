// IsIDOfWhitelistedEntity reports whether the given normalized tax ID (CNPJ/EIN/BN)
// belongs to any entity in the tax whitelist (i.e. a government body that receives
// taxes). Used to block government-payer mining (government→government).
//
// Aceita o ID inteiro OU, quando o comprovante mascara parte do número
// (ex: CNPJ "**392.130/0001-**" → miolo "3921300001"), faz match por subconjunto:
// se o miolo visível estiver CONTIDO no ID da whitelist (ou vice-versa) e for
// longo o suficiente para não gerar falso positivo, considera match.
func IsIDOfWhitelistedEntity(normalizedID string) bool {
	id := strings.ToUpper(strings.TrimSpace(normalizedID))
	if id == "" {
		return false
	}
	for _, ids := range taxEntityIDs {
		for _, full := range ids {
			if id == full {
				return true
			}
			// Match por subconjunto (CNPJ/EIN/BN mascarado): exigimos um miolo de
			// no mínimo 6 dígitos para evitar falso positivo com trechos curtos.
			fullNorm := strings.ToUpper(strings.TrimSpace(full))
			if len(id) >= 6 && len(fullNorm) >= 6 &&
				(strings.Contains(fullNorm, id) || strings.Contains(id, fullNorm)) {
				return true
			}
		}
	}
	return false
}

// WhitelistedEntityForID returns the whitelist slug (e.g. "br:iptu_sao_paulo")
// whose tax ID matches the given normalized ID, accepting the same masked /
// subset rule as IsIDOfWhitelistedEntity. Used to recognise the receiving tax
// authority straight from the receipt's CNPJ/EIN/BN — rail-agnostic: a PIX to a
// municipality counts the same as a boleto or DARF.
func WhitelistedEntityForID(normalizedID string) (string, bool) {
	id := strings.ToUpper(strings.TrimSpace(normalizedID))
	if id == "" {
		return "", false
	}
	// Exact match first.
	for slug, ids := range taxEntityIDs {
		for _, full := range ids {
			if id == strings.ToUpper(strings.TrimSpace(full)) {
				return slug, true
			}
		}
	}
	// Masked/subset match (mesma guarda de IsIDOfWhitelistedEntity).
	for slug, ids := range taxEntityIDs {
		for _, full := range ids {
			fullNorm := strings.ToUpper(strings.TrimSpace(full))
			if len(id) >= 6 && len(fullNorm) >= 6 &&
				(strings.Contains(fullNorm, id) || strings.Contains(id, fullNorm)) {
				return slug, true
			}
		}
	}
	return "", false
}

// TaxEntityIDs returns the well-known tax IDs (CNPJ/EIN/BN) of a whitelist
// slug — e.g. "br:iptu_sao_paulo" → ["46392130000118"]. É o identificador PÚBLICO
// do governo que recebeu o imposto: vai para o evento da mineração junto ao
// valor, para o recibo ficar verificável sem depender do slug.
func TaxEntityIDs(slug string) []string {
	ids, ok := taxEntityIDs[strings.ToLower(strings.TrimSpace(slug))]
	if !ok {
		return nil
	}
	out := make([]string, len(ids))
	copy(out, ids)
	return out
}

// NormalizeTaxID normalizes a raw tax ID (CNPJ/EIN/BN) to uppercase digits/letters.
func NormalizeTaxID(raw string) string {
	return strings.ToUpper(strings.Map(func(r rune) rune {
		if (r >= '0' && r <= '9') || (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') {
			return r
		}
		return -1
	}, raw))
}
